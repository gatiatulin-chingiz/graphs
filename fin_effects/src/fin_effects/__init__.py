"""Расчёт финансового эффекта от сервиса графовой аналитики.

Пакет разбит на слои, повторяющие пайплайн:

``config``
    Пути, имена колонок, параметры методики.
``io_utils``
    Чтение/запись промежуточных артефактов (pkl, parquet, xlsx).
``excel_beneficiaries``
    Загрузка выгрузок сервиса (xlsx-файлы с участниками групп).
``queries``
    SQL-запросы к OISUU (Losses / Payments / Cards).
``loaders``
    Загрузка ``losses`` / ``payments`` / ``cards`` (из БД или из файлов).
``preprocess``
    Очистка, нормализация, дедупликация, ключи сущностей.
``groups``
    Формирование идентификаторов групп и дат обнаружения.
``effect``
    Ядро методики: классы релевантности группы и финансовый эффект.
``legacy``
    Воспроизведение исходной (до рефакторинга) логики — для сравнения.
``reporting``
    Сводные таблицы, графики, экспорт итогов.
``synth``
    Генератор синтетических данных для прогонки пайплайна.
"""

